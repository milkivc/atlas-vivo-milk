def http(url, method="GET", payload=None, headers=None, timeout=120):
    req = urllib.request.Request(
        url,
        data=None if payload is None else json.dumps(payload).encode(),
        method=method,
        headers=headers or {},
    )
    with urllib.request.urlopen(req, timeout=timeout) as res:
        return res.status, res.read()


def comment(msg):
    print(msg, flush=True)
    if not GH:
        return
    http(
        f"https://api.github.com/repos/{REPO}/issues/35/comments",
        "POST",
        {"body": msg},
        {
            "Authorization": "Bearer " + GH,
            "Content-Type": "application/json",
            "Accept": "application/vnd.github+json",
        },
        60,
    )


def connect(password):
    ftp = ftplib.FTP_TLS(context=ssl.create_default_context(), timeout=300)
    ftp.connect("troi.ptservidor.net", 21)
    ftp.login("migration@associacaomilk.pt", password)
    ftp.prot_p()
    ftp.voidcmd("TYPE I")
    return ftp


def ensure(ftp, path):
    ftp.cwd("/")
    for part in [p for p in path.split("/") if p]:
        try:
            ftp.mkd(part)
        except ftplib.all_errors:
            pass
        ftp.cwd(part)


def safe_parts(path):
    raw = path.replace("\\", "/").split("/")
    out = []
    for part in raw:
        if part in ("", ".", ".."):
            continue
        part = re.sub(r'[\\:*?"<>|\x00-\x1f]', "_", part).strip(" .")
        out.append((part or "sem-nome")[:180])
    return out


def retr_json(ftp, path):
    data = bytearray()
    ftp.retrbinary("RETR " + path, data.extend, blocksize=1048576)
    return json.loads(data)


class HashReader:
    def __init__(self, src):
        self.src = src
        self.hash = hashlib.sha256()
        self.count = 0

    def read(self, n=-1):
        data = self.src.read(n)
        if data:
            self.hash.update(data)
            self.count += len(data)
        return data


